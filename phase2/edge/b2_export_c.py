"""B2. Write the chosen forest and the filter as C, plus "golden" test data.

Produces, inside phase2/edge/c/:
    edge_rf.h        every tree flattened into a few constant arrays (stays in flash)
    edge_filter.h    the band-pass filter coefficients (same numbers as phase2/frontend.py)
and inside tests/golden_edge/:
    raw.csv          130 s of raw sensor-like samples, one per line
    windows.csv      the calibrated windows Python's front end makes from them
    features.csv     Python's 13 features for each of those windows
    proba.csv        Python's 5 class probabilities for each window
The C test (B3) must reproduce all three from raw.csv alone.

    python -m phase2.edge.b2_export_c
"""
import os

import joblib
import numpy as np

import config
from phase2.common import ensure_dir, load_corpus, load_raw_record
from phase2.contracts import EDGE_MODEL, FS
from phase2.frontend import StreamingFrontEnd, device_like, filter_sections
from selfdiag import features as F
from selfdiag import preprocess as P

HERE = os.path.dirname(os.path.abspath(__file__))
C_DIR = os.path.join(HERE, "c")
GOLD = ensure_dir(os.path.join(config.ROOT, "tests", "golden_edge"))


def cfloat(v, digits=9):
    s = "%.*g" % (digits, v)
    if not any(ch in s for ch in ".en"):
        s += ".0"
    return s


def c_array(name, ctype, vals, fmt, per_line=12):
    lines, cur = [], []
    for v in vals:
        if fmt == "float":
            cur.append(cfloat(v) + "f")
        elif fmt == "double":
            cur.append(cfloat(v, 17))
        else:
            cur.append(fmt % v)
        if len(cur) == per_line:
            lines.append("  " + ", ".join(cur) + ","); cur = []
    if cur:
        lines.append("  " + ", ".join(cur) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


rf = joblib.load(EDGE_MODEL)
NC = len(config.CLASSES)
feat, thr, left, right, leaf, roots, leafv = [], [], [], [], [], [], []
for est in rf.estimators_:
    t = est.tree_
    off = len(feat)
    roots.append(off)
    for i in range(t.node_count):
        if t.children_left[i] == -1:
            v = t.value[i][0].astype(float)
            v = v / max(v.sum(), 1e-12)
            full = np.zeros(NC)
            full[rf.classes_.astype(int)] = v          # class order = config.CLASSES
            leaf.append(len(leafv) // NC)
            leafv.extend(full.tolist())
            feat.append(255); thr.append(0.0); left.append(-1); right.append(-1)
        else:
            feat.append(int(t.feature[i])); thr.append(float(t.threshold[i]))
            left.append(off + int(t.children_left[i])); right.append(off + int(t.children_right[i]))
            leaf.append(-1)
n = len(feat)
assert n < 32767, "too many nodes for int16 child indexes; pick a smaller forest"
hdr = ["/* Generated by phase2/edge/b2_export_c.py from models/edge_rf.joblib. Do not edit. */",
       f"/* {len(roots)} trees, {n} nodes, {len(leafv) // NC} leaves, classes: {', '.join(config.CLASSES)} */",
       "#ifndef EDGE_RF_H", "#define EDGE_RF_H", "#include <stdint.h>",
       f"#define EDGE_RF_NTREES {len(roots)}", f"#define EDGE_RF_NNODES {n}", f"#define EDGE_RF_NCLASS {NC}", "",
       c_array("EDGE_RF_FEAT", "uint8_t", feat, "%d", 24),
       c_array("EDGE_RF_THR", "float", thr, "float", 8),
       c_array("EDGE_RF_LEFT", "int16_t", left, "%d", 16),
       c_array("EDGE_RF_RIGHT", "int16_t", right, "%d", 16),
       c_array("EDGE_RF_LEAF", "int16_t", leaf, "%d", 16),
       c_array("EDGE_RF_ROOT", "int16_t", roots, "%d", 16),
       c_array("EDGE_RF_LEAFV", "float", leafv, "float", 5), "#endif", ""]
open(os.path.join(C_DIR, "edge_rf.h"), "w").write("\n".join(hdr))

sos = filter_sections(FS, double=True)
fh = ["/* Generated by phase2/edge/b2_export_c.py. Same filter as phase2/frontend.py. */",
      "#ifndef EDGE_FILTER_H", "#define EDGE_FILTER_H",
      f"#define EDGE_NSECTIONS {sos.shape[0]}",
      "/* each row: b0 b1 b2 a0 a1 a2 (a0 is always 1) */",
      c_array("EDGE_SOS", "double", sos.ravel().tolist(), "double", 6), "#endif", ""]
open(os.path.join(C_DIR, "edge_filter.h"), "w").write("\n".join(fh))

# golden data: 130 s from one record = warm-up + calibration + 2 windows ... plus a few more
names = [str(x) for x in load_corpus()["group_names"]]
raw, fs_in = load_raw_record(names[0], n_surrogate=len(names))
sig = device_like(P.resample_to(raw, fs_in, FS))[: FS * 160]
fe = StreamingFrontEnd(double=True)
wins = np.asarray([w for w, _ in fe.push(sig)])
feats = np.asarray([F.extract(w, FS) for w in wins])
proba = rf.predict_proba(feats)
np.savetxt(os.path.join(GOLD, "raw.csv"), sig, fmt="%.6f")
np.savetxt(os.path.join(GOLD, "windows.csv"), wins, delimiter=",", fmt="%.9g")
np.savetxt(os.path.join(GOLD, "features.csv"), feats, delimiter=",", fmt="%.9g")
np.savetxt(os.path.join(GOLD, "proba.csv"), proba, delimiter=",", fmt="%.9g")
kb = (n * config.BYTES_PER_NODE + len(leafv) * 4) / 1024
print(f"wrote c/edge_rf.h ({len(roots)} trees, {n} nodes, about {kb:.0f} KB in flash) and c/edge_filter.h")
print(f"wrote golden data: {len(sig)} raw samples -> {len(wins)} windows, in tests/golden_edge/")
